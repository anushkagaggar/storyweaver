async def test_extension_tables_and_search_indexes_exist(session: AsyncSession) -> None:
    extension = await session.execute(text("SELECT extname FROM pg_extension WHERE extname = 'vector'"))
    assert extension.scalar_one() == "vector"

    rows = await session.execute(
        text("SELECT indexname, indexdef FROM pg_indexes WHERE tablename = 'tale_chunks'")
    )
    definitions = {name: definition for name, definition in rows}

    assert "USING hnsw" in definitions["ix_tale_chunks_embedding"]
    assert "vector_cosine_ops" in definitions["ix_tale_chunks_embedding"]
    assert "USING gin" in definitions["ix_tale_chunks_tsv"]
    assert {"ix_tale_chunks_theme", "ix_tale_chunks_age_band", "uq_tale_chunks_tale_id_position"} <= set(
        definitions
    )


async def test_chunk_round_trips_and_postgres_fills_the_text_search_column(session: AsyncSession) -> None:
    chunk = _chunk("gutenberg:1", 0, "A tiny dragon was afraid of the dark.", _vec(0, 5, value=0.5))
    session.add(chunk)
    await session.commit()
    await session.refresh(chunk)

    assert chunk.tsv is not None
    assert "'dragon'" in chunk.tsv  # generated by Postgres from `text`; we never wrote it
    assert len(chunk.embedding) == EMBEDDING_DIM
    assert chunk.embedding[0] == pytest.approx(0.5)
    assert chunk.embedding[1] == 0.0


async def test_nearest_neighbours_by_cosine_distance(session: AsyncSession) -> None:
    session.add_all(
        [
            _chunk("gutenberg:1", 0, "first", _vec(0)),
            _chunk("gutenberg:2", 0, "second", _vec(1)),
            _chunk("gutenberg:3", 0, "third", _vec(2)),
        ]
    )
    await session.commit()

    query = _vec()
    query[0], query[1] = 1.0, 0.2  # mostly "first", a little "second"
    nearest = await session.scalars(
        select(TaleChunkRow).order_by(TaleChunkRow.embedding.cosine_distance(query)).limit(3)
    )

    assert [chunk.text for chunk in nearest] == ["first", "second", "third"]


async def test_full_text_search_uses_the_generated_column(session: AsyncSession) -> None:
    session.add_all(
        [
            _chunk("gutenberg:1", 0, "A small dragon hid in a cosy cave.", _vec(0)),
            _chunk("gutenberg:2", 0, "A hedgehog splashed in a puddle.", _vec(1)),
        ]
    )
    await session.commit()

    # .match() renders `tsv @@ plainto_tsquery('english', 'dragons')`.
    found = await session.scalars(
        select(TaleChunkRow).where(TaleChunkRow.tsv.match("dragons", postgresql_regconfig="english"))
    )

    # 'dragons' also matches 'dragon': the English configuration stems words.
    assert [chunk.tale_id for chunk in found] == ["gutenberg:1"]


async def test_a_tale_position_is_stored_once(session: AsyncSession) -> None:
    session.add(_chunk("gutenberg:1", 0, "one", _vec(0)))
    await session.commit()

    session.add(_chunk("gutenberg:1", 0, "same place again", _vec(1)))
    with pytest.raises(IntegrityError):
        await session.commit()
    await session.rollback()


async def test_the_database_rejects_a_vector_of_the_wrong_size(session: AsyncSession) -> None:
    session.add(_chunk("gutenberg:1", 0, "too short", [1.0, 2.0, 3.0]))

    with pytest.raises(DBAPIError, match="dimensions"):
        await session.commit()
    await session.rollback()


async def test_a_story_bible_goes_when_its_story_goes(session: AsyncSession) -> None:
    story = StoryRow(prompt_text="a dragon", age_band="4-6", num_scenes=5)
    session.add(story)
    await session.flush()
    session.add(StoryBibleRow(story_id=story.id, bible={"characters": ["Pip"]}))  # no embedding yet: allowed
    await session.commit()

    await session.delete(story)
    await session.commit()

    remaining = await session.execute(text("SELECT count(*) FROM story_bibles"))
    assert remaining.scalar_one() == 0


async def test_a_story_bible_needs_a_real_story(session: AsyncSession) -> None:
    session.add(StoryBibleRow(story_id=uuid.uuid4(), bible={}))

    with pytest.raises(IntegrityError):
        await session.commit()
    await session.rollback()
